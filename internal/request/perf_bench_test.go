// BenchmarkGenerateEndToEnd exercises prompt assembly, the (fake) model
// call, sanitation, and verification together on a mid-size diff.
func BenchmarkGenerateEndToEnd(b *testing.B) {
	diff := benchDiff(50, 30)
	llm := &scriptLLM{name: "s", responses: []string{benchMessage(50)}}
	client := NewClientWithGenerator(llm, "m")

	b.ReportAllocs()

	for b.Loop() {
		if _, _, err := client.GenerateCommitMessageWithContent(
			context.Background(), Change{Diff: diff}, "", DetailStandard, "", nil, defaultWrapLine,
		); err != nil {
			b.Fatal(err)
		}
	}
}

package git

import (
	"context"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"strings"
)

// hooksPathKey is git's global core.hooksPath configuration key.
const hooksPathKey = "core.hooksPath"

// HookType represents the type of git hook.
type HookType string

const (
	PrepareCommitMsg HookType = "prepare-commit-msg"
	CommitMsg        HookType = "commit-msg"
)

// InstallHook installs a git hook that calls git-message.
// hookDir is typically .git/hooks or a global hooks directory.
// binaryPath is the absolute path to the gud binary, resolved at install time.
func InstallHook(hookDir string, hookType HookType, binaryPath string) error {
	hookPath := filepath.Join(hookDir, string(hookType))

	content := buildHookScript(binaryPath)

	//nolint:gosec // git hooks must be executable for git to invoke them
	if err := os.WriteFile(hookPath, []byte(content), 0755); err != nil {
		return fmt.Errorf("failed to write hook file: %w", err)
	}

	slog.Debug("installed hook", "path", hookPath, "type", hookType)

	return nil
}

// buildHookScript creates the hook script content using the full binary path
// so the hook works even if the binary is not on $PATH.
// The binary path is single-quoted and embedded single quotes are escaped
// to prevent shell injection via malicious binary paths.
func buildHookScript(binaryPath string) string {
	escaped := strings.ReplaceAll(binaryPath, "'", "'\\''")

	return `#!/bin/sh
# Auto-generated by gud
# Generates commit message based on staged changes

'` + escaped + `' hook run "$1"
`
}

// UninstallHook removes a git hook.
func UninstallHook(hookDir string, hookType HookType) error {
	hookPath := filepath.Join(hookDir, string(hookType))

	if err := os.Remove(hookPath); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("failed to remove hook file: %w", err)
	}

	slog.Debug("uninstalled hook", "path", hookPath)

	return nil
}

// GetHookDir returns the appropriate hooks directory.
// If global is true, returns ~/.config/gud/hooks/ (gud's XDG config home,
// matching the global config location), otherwise .git/hooks/.
func GetHookDir(global bool) (string, error) {
	if global {
		home, err := os.UserHomeDir()
		if err != nil {
			return "", fmt.Errorf("failed to get home directory: %w", err)
		}

		return filepath.Join(home, ".config", "gud", "hooks"), nil
	}

	return filepath.Join(".git", "hooks"), nil
}

// GetGlobalHooksPath returns the global core.hooksPath configuration value,
// or an empty string when it is unset. Git does not automatically scan a
// custom global hooks directory, so hooks installed outside .git/hooks only
// run when core.hooksPath points at them.
func GetGlobalHooksPath(ctx context.Context) (string, error) {
	value, set, err := gitConfigGlobal(ctx, hooksPathKey)
	if err != nil {
		return "", err
	}

	if !set {
		return "", nil
	}

	return value, nil
}

// SetGlobalHooksPath sets the global core.hooksPath configuration value.
func SetGlobalHooksPath(ctx context.Context, dir string) error {
	if _, err := runGit(ctx, "config", "--global", hooksPathKey, dir); err != nil {
		return fmt.Errorf("set global core.hooksPath: %w", err)
	}

	return nil
}

// UnsetGlobalHooksPath removes the global core.hooksPath configuration value.
// It is a no-op when the key is not set.
func UnsetGlobalHooksPath(ctx context.Context) error {
	if _, err := runGit(ctx, "config", "--global", "--unset", hooksPathKey); err != nil {
		if isGitExitCode(err, gitExitCodeMissingValue) {
			return nil
		}

		return fmt.Errorf("unset global core.hooksPath: %w", err)
	}

	return nil
}

package git

import (
	"context"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"strings"

	"gud/internal/request"
)

// HookType represents the type of git hook.
type HookType string

const (
	PrepareCommitMsg HookType = "prepare-commit-msg"
	CommitMsg        HookType = "commit-msg"
)

// InstallHook installs a git hook that calls git-message.
// hookDir is typically .git/hooks or a global hooks directory.
func InstallHook(hookDir string, hookType HookType) error {
	hookPath := filepath.Join(hookDir, string(hookType))

	content := buildHookScript()

	if err := os.WriteFile(hookPath, []byte(content), 0755); err != nil {
		return fmt.Errorf("failed to write hook file: %w", err)
	}

	slog.Debug("installed hook", "path", hookPath, "type", hookType)
	return nil
}

// buildHookScript creates the hook script content.
func buildHookScript() string {
	return `#!/bin/sh
# Auto-generated by gud
# Generates commit message based on staged changes

gud hook run "$1"
`
}

// RunHookMode generates a commit message and writes it to the message file.
func RunHookMode(ctx context.Context, msgFile, apiKey string, detailLevel request.DetailLevel, hint string, persona request.PersonaName) error {
	diff, err := getStagedDiffOrSkip(ctx)
	if err != nil {
		return fmt.Errorf("failed to get staged diff: %w", err)
	}
	if diff == "" {
		return nil
	}

	client, err := request.NewClient(apiKey)
	if err != nil {
		return fmt.Errorf("failed to create request client: %w", err)
	}

	return generateAndWriteMsg(client, ctx, diff, detailLevel, hint, persona, msgFile)
}

// getStagedDiffOrSkip returns the staged diff, or an empty string if there are no staged changes.
func getStagedDiffOrSkip(ctx context.Context) (string, error) {
	diff, err := GetStagedDiff(ctx)
	if err != nil {
		return "", err
	}
	if strings.TrimSpace(diff) == "" {
		return "", nil
	}
	return diff, nil
}

// generateAndWriteMsg generates a commit message and writes it to the message file.
func generateAndWriteMsg(client *request.Client, ctx context.Context, diff string, detailLevel request.DetailLevel, hint string, persona request.PersonaName, msgFile string) error {
	msg, err := client.GenerateCommitMessage(ctx, diff, "", detailLevel, hint, persona)
	if err != nil {
		return fmt.Errorf("failed to generate commit message: %w", err)
	}

	if err := os.WriteFile(msgFile, []byte(msg), 0644); err != nil {
		return fmt.Errorf("failed to write message file: %w", err)
	}
	return nil
}

// UninstallHook removes a git hook.
func UninstallHook(hookDir string, hookType HookType) error {
	hookPath := filepath.Join(hookDir, string(hookType))

	if err := os.Remove(hookPath); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("failed to remove hook file: %w", err)
	}

	slog.Debug("uninstalled hook", "path", hookPath)
	return nil
}

// GetHookDir returns the appropriate hooks directory.
// If global is true, returns ~/.git-hooks/, otherwise .git/hooks/
func GetHookDir(global bool) (string, error) {
	if global {
		home, err := os.UserHomeDir()
		if err != nil {
			return "", fmt.Errorf("failed to get home directory: %w", err)
		}
		return filepath.Join(home, ".git-hooks"), nil
	}

	return filepath.Join(".git", "hooks"), nil
}
